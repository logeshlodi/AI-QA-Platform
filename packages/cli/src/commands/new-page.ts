import fs from 'node:fs';
import path from 'node:path';
import { format, resolveConfig } from 'prettier';
import { parseAriaSnapshot, type AriaCandidate } from '@aiqa/ai-engine';

/** Roles worth a locator in a page object: things a user reads or acts on. */
const ROLE_SUFFIX: Record<string, string> = {
  button: 'Button',
  link: 'Link',
  textbox: 'Field',
  searchbox: 'Search',
  checkbox: 'Checkbox',
  radio: 'Radio',
  combobox: 'Select',
  heading: 'Heading',
};
const MAX_LOCATORS = 25;

export interface PageElement extends AriaCandidate {
  property: string;
}

/** A single-quoted TypeScript string literal, in the project's quote style. */
const q = (value: string): string => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const words = (text: string): string[] => text.match(/[A-Za-z0-9]+/g) ?? [];

/** "Add to cart" + button -> addToCartButton. */
export function propertyName(name: string, role: string): string {
  const parts = words(name).slice(0, 5);
  const camel = parts
    .map((w, i) => (i === 0 ? w.toLowerCase() : w[0]!.toUpperCase() + w.slice(1).toLowerCase()))
    .join('');
  const base = /^[a-z]/.test(camel) ? camel : `el${camel}`;
  return base + (ROLE_SUFFIX[role] ?? '');
}

/** The elements of an aria snapshot that get a locator, each with a unique property name. */
export function pageElements(snapshot: string): PageElement[] {
  const used = new Set<string>();
  const elements: PageElement[] = [];
  for (const candidate of parseAriaSnapshot(snapshot)) {
    if (!(candidate.role in ROLE_SUFFIX) || candidate.name.length > 40 || words(candidate.name).length === 0)
      continue;
    let property = propertyName(candidate.name, candidate.role);
    for (let n = 2; used.has(property); n++) property = `${propertyName(candidate.name, candidate.role)}${n}`;
    used.add(property);
    elements.push({ ...candidate, property });
    if (elements.length === MAX_LOCATORS) break;
  }
  return elements;
}

export const pascal = (name: string): string =>
  words(name)
    .map((w) => w[0]!.toUpperCase() + w.slice(1))
    .join('');
export const kebab = (name: string): string =>
  words(name.replace(/([a-z0-9])([A-Z])/g, '$1 $2'))
    .map((w) => w.toLowerCase())
    .join('-');

export interface NewPageOptions {
  /** "Login", "order history". Becomes LoginPage / login.page.ts. */
  name: string;
  /** Folder under src/pages: one per site. */
  site: string;
  /** Path the page object opens, relative to the project's baseURL. */
  urlPath: string;
  /** Target name from the registry, used by the spec's test.use(). */
  target: string;
  /** From `locator.ariaSnapshot()`. Empty means a page object with no locators yet. */
  ariaSnapshot?: string;
}

export interface GeneratedFile {
  path: string;
  content: string;
}

/** Renders the page object and its starter spec. Pure: writes nothing. */
export function renderPage(options: NewPageOptions): GeneratedFile[] {
  const className = `${pascal(options.name)}Page`;
  const file = kebab(options.name);
  const elements = pageElements(options.ariaSnapshot ?? '');
  const fields = elements.map((e) => `  readonly ${e.property}: Locator;`).join('\n');
  const assigns = elements
    .map(
      (e) =>
        `    this.${e.property} = page\n      .getByRole(${q(e.role)}, { name: ${q(e.name)}, exact: true })\n      .describe(${q(`${e.name} ${e.role}`)});`,
    )
    .join('\n');
  const pageObject = `import type { Locator, Page } from '@playwright/test';
import { BasePage } from '../base.page';

/**
 * Generated by \`aiqa new page\`${elements.length ? " from the page's accessibility tree" : ''}.
 * Rename locators to match what they mean, add the user actions a test needs, and delete the rest.
 */
export class ${className} extends BasePage {
  protected readonly path = ${q(options.urlPath)};
${fields || '  // No named elements were found. Add locators here.'}

  constructor(page: Page) {
    super(page);
${assigns}
  }
}
`;
  const first = elements.find((e) => e.role === 'heading') ?? elements[0];
  const spec = `import { expect, test } from '../../src/fixtures';
import { ${className} } from '../../src/pages/${options.site}/${file}.page';

test.use({ targetName: ${q(options.target)} });

// Generated by \`aiqa new page\`: a starting point, not a finished test.
test.describe('${pascal(options.name)} page', { tag: '@generated' }, () => {
  test('opens and shows its main content', async ({ page }) => {
    const ${file.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase())}Page = new ${className}(page);
    await ${file.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase())}Page.goto();
${
  first
    ? `    await expect(${file.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase())}Page.${first.property}).toBeVisible();`
    : `    await expect(page).toHaveURL(new RegExp(${q(options.urlPath.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))}));`
}
  });
});
`;
  return [
    { path: path.join('src', 'pages', options.site, `${file}.page.ts`), content: pageObject },
    { path: path.join('tests', 'generated', `${file}.spec.ts`), content: spec },
  ];
}

/** Formats generated code with the repository's own Prettier settings, so it looks hand-written. */
export async function formatFiles(root: string, files: GeneratedFile[]): Promise<GeneratedFile[]> {
  return Promise.all(
    files.map(async (f) => {
      const filepath = path.join(root, f.path);
      const config = (await resolveConfig(filepath)) ?? {};
      return { ...f, content: await format(f.content, { ...config, filepath }) };
    }),
  );
}

/** Writes generated files under a root, refusing to overwrite unless forced. Returns what it wrote. */
export function writeFiles(root: string, files: GeneratedFile[], force = false): string[] {
  const clashes = files.filter((f) => fs.existsSync(path.join(root, f.path)));
  if (clashes.length > 0 && !force) {
    throw new Error(`Not overwriting ${clashes.map((f) => f.path).join(', ')}. Use --force to replace them.`);
  }
  for (const f of files) {
    fs.mkdirSync(path.dirname(path.join(root, f.path)), { recursive: true });
    fs.writeFileSync(path.join(root, f.path), f.content);
  }
  return files.map((f) => f.path);
}
