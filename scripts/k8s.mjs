#!/usr/bin/env node
// The test stack on a local Kubernetes cluster (kind), and the test suites as Kubernetes Jobs.
//
//   pnpm k8s:up                      create the cluster (once), build and load the images, install the chart
//   pnpm k8s:test data               Postgres, MongoDB and Kafka suites, inside the cluster
//   pnpm k8s:test ui [playwright args]   UI suite on the shared browser server (default --project=chromium)
//   pnpm k8s:test load [smoke|load|stress]   k6 against the order service
//   pnpm k8s:status                  what is running
//   pnpm k8s:down                    delete the cluster
//
// Needs Docker, kind, kubectl and Helm on PATH. Results (HTML reports, run history, k6 summaries)
// land in this repository's .aiqa folder, which the cluster mounts.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const CLUSTER = 'aiqa';
const NAMESPACE = 'aiqa';
const RELEASE = 'aiqa';
const CHART = path.join(ROOT, 'infrastructure', 'kubernetes', 'aiqa-stack');
const DATA = path.join(ROOT, '.aiqa');
const STATE = path.join(DATA, 'k8s', 'images.json');
// Keep in step with nodePorts in the chart's values.yaml: kind publishes each on localhost.
const NODE_PORTS = [30088, 30464, 30432, 30017, 30092, 30090, 30091, 30300, 30333];
const SUITES = ['data', 'ui', 'load'];

/** Runs a command. `capture` returns its output; otherwise output goes straight to the terminal. */
function run(command, args, { capture = false, input, allowFail = false, env } = {}) {
  const result = spawnSync(command, args, {
    cwd: ROOT,
    input,
    encoding: 'utf8',
    env: env ? { ...process.env, ...env } : process.env,
    stdio: [input === undefined ? 'inherit' : 'pipe', capture ? 'pipe' : 'inherit', 'inherit'],
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.error)
    throw new Error(`Could not run ${command}: ${result.error.message}. Is it installed and on PATH?`);
  if (result.status !== 0 && !allowFail)
    throw new Error(`${command} ${args.join(' ')} exited with ${result.status}`);
  return capture ? result.stdout.trim() : result.status;
}
const kubectl = (args, options) =>
  run('kubectl', ['--context', `kind-${CLUSTER}`, '-n', NAMESPACE, ...args], options);
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

function clusterExists() {
  return run('kind', ['get', 'clusters'], { capture: true }).split(/\r?\n/).includes(CLUSTER);
}

/** The kind configuration, written fresh because it holds this checkout's absolute path. */
function writeKindConfig() {
  // Kubernetes 1.35+ refuses to start its kubelet on a cgroup v1 host unless told otherwise. Docker
  // Desktop on an older WSL2 setup is such a host (found 20 Nov 2026: Kubernetes 1.37 in kind 0.33).
  // Opting in keeps it working; switching WSL2 to cgroup v2 is the lasting fix.
  const cgroupV1 = run('docker', ['info', '--format', '{{.CgroupVersion}}'], { capture: true }) === '1';
  if (cgroupV1) {
    console.warn(
      '> Docker runs on cgroup v1, which Kubernetes no longer supports by default: allowing it for this' +
        ' cluster (failCgroupV1: false). Lasting fix: cgroup v2 (see infrastructure/kubernetes/README.md).',
    );
  }
  const file = path.join(DATA, 'k8s', 'kind-config.yaml');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const ports = NODE_PORTS.map(
    (port) => `      - { containerPort: ${port}, hostPort: ${port}, listenAddress: 127.0.0.1 }`,
  ).join('\n');
  fs.writeFileSync(
    file,
    `# Generated by scripts/k8s.mjs.
kind: Cluster
apiVersion: kind.x-k8s.io/v1alpha4
nodes:
  - role: control-plane
    # This checkout's .aiqa folder, where test Jobs write reports and run history.
    extraMounts:
      - { hostPath: ${JSON.stringify(DATA)}, containerPath: /aiqa-data }
    # The chart's node ports, published on localhost only.
    extraPortMappings:
${ports}
${
  cgroupV1
    ? `kubeadmConfigPatches:
  - |
    kind: KubeletConfiguration
    failCgroupV1: false
`
    : ''
}`,
  );
  return file;
}

/** Builds an image and tags it with its own digest, so a changed image gets a new tag and rolls out. */
function build(name, dockerfile) {
  console.log(`\n> building ${name}`);
  run('docker', ['build', '-f', dockerfile, '-t', `${name}:latest`, '.']);
  const id = run('docker', ['image', 'inspect', '-f', '{{.Id}}', `${name}:latest`], { capture: true });
  const tag = `${name}:${id.replace('sha256:', '').slice(0, 12)}`;
  run('docker', ['tag', `${name}:latest`, tag]);
  return tag;
}

/** Loads an image into the kind node unless it is there already (the tests image is large). */
function load(tag) {
  const images = run('docker', ['exec', `${CLUSTER}-control-plane`, 'crictl', 'images', '-o', 'json'], {
    capture: true,
  });
  if (images.includes(`"docker.io/${tag}"`)) return console.log(`> ${tag} already in the cluster`);
  console.log(`> loading ${tag} into the cluster`);
  run('kind', ['load', 'docker-image', tag, '--name', CLUSTER]);
}

function images() {
  if (!fs.existsSync(STATE)) throw new Error('The stack is not installed. Run `pnpm k8s:up` first.');
  return JSON.parse(fs.readFileSync(STATE, 'utf8'));
}
const imageArgs = (tags) => [
  '--set',
  `images.orderService=${tags.orderService}`,
  '--set',
  `images.tests=${tags.tests}`,
];

function up() {
  run('docker', ['info', '--format', '{{.ServerVersion}}'], { capture: true });
  if (!clusterExists()) {
    console.log(`> creating kind cluster "${CLUSTER}"`);
    run('kind', ['create', 'cluster', '--name', CLUSTER, '--config', writeKindConfig(), '--wait', '120s']);
  }
  const tags = {
    orderService: build('aiqa/order-service', 'apps/order-service/Dockerfile'),
    tests: build('aiqa/tests', 'infrastructure/docker/Dockerfile'),
  };
  load(tags.orderService);
  load(tags.tests);
  console.log('\n> installing the chart (waits until every pod is ready)');
  run('helm', [
    'upgrade',
    '--install',
    RELEASE,
    CHART,
    '--kube-context',
    `kind-${CLUSTER}`,
    '-n',
    NAMESPACE,
    '--create-namespace',
    '--wait',
    '--timeout',
    '10m',
    ...imageArgs(tags),
  ]);
  fs.mkdirSync(path.dirname(STATE), { recursive: true });
  fs.writeFileSync(STATE, JSON.stringify(tags, null, 2));
}

async function waitForPod(job) {
  for (let i = 0; i < 300; i++) {
    const phase = kubectl(
      ['get', 'pods', '-l', `job-name=${job}`, '-o', 'jsonpath={.items[0].status.phase}'],
      {
        capture: true,
        allowFail: true,
      },
    );
    if (['Running', 'Succeeded', 'Failed'].includes(phase)) return;
    await sleep(2000);
  }
  throw new Error(`The pod of ${job} did not start within 10 minutes (kubectl describe job ${job}).`);
}

/** The exit code of the Job's container, once it has finished. */
async function exitCodeOf(job) {
  for (let i = 0; i < 600; i++) {
    const code = kubectl(
      [
        'get',
        'pods',
        '-l',
        `job-name=${job}`,
        '-o',
        'jsonpath={.items[0].status.containerStatuses[0].state.terminated.exitCode}',
      ],
      { capture: true, allowFail: true },
    );
    if (code !== '') return Number(code);
    await sleep(1000);
  }
  return 1;
}

async function test(suite, extra) {
  if (!SUITES.includes(suite)) throw new Error(`Unknown suite "${suite}". Use one of: ${SUITES.join(', ')}`);
  const tags = images();
  const id = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
  const job = `aiqa-${suite}-${id}`;
  const set = ['--set', `job.name=${suite}`, '--set', `job.id=${id}`, ...imageArgs(tags)];
  if (suite === 'ui' && extra.length > 0) set.push('--set-string', `job.args=${extra.join(' ')}`);
  const profile = suite === 'load' ? (extra[0] ?? 'smoke') : undefined;
  if (profile) {
    set.push('--set', `job.profile=${profile}`);
    // Helm reads backslashes in --set values as escapes, so Windows paths go in with forward slashes.
    const script = path.join(ROOT, 'packages', 'load-tests', 'scripts', 'order-flow.js');
    set.push('--set-file', `k6.script=${script.replaceAll('\\', '/')}`);
  }
  const manifest = run(
    'helm',
    ['template', RELEASE, CHART, '-n', NAMESPACE, '--show-only', `templates/jobs/${suite}.yaml`, ...set],
    { capture: true },
  );
  const startedAt = new Date();
  kubectl(['apply', '-f', '-'], { input: manifest });
  console.log(`> ${job}: waiting for its pod`);
  await waitForPod(job);
  kubectl(['logs', '-f', `job/${job}`], { allowFail: true });
  const code = await exitCodeOf(job);

  if (suite === 'load') {
    // The k6 Job wrote its summary into .aiqa; record it in the run history here, as `pnpm perf:load` does.
    const summary = path.join(DATA, 'k8s', `load-${id}`, 'summary.json');
    run(
      process.execPath,
      [
        '--import',
        'tsx',
        'packages/load-tests/src/run.ts',
        '--record',
        profile,
        String(code),
        summary,
        startedAt.toISOString(),
      ],
      { env: { AIQA_PUSHGATEWAY: process.env.AIQA_PUSHGATEWAY ?? 'http://localhost:30091' } },
    );
  } else {
    console.log(`\nHTML report: ${path.join(DATA, 'k8s', `${suite}-${id}`, 'report', 'index.html')}`);
  }
  console.log(
    `${job} ${code === 0 ? 'passed' : `failed (exit code ${code})`}. Grafana: http://localhost:30300`,
  );
  process.exitCode = code;
}

function status() {
  kubectl(['get', 'pods,jobs,services', '-o', 'wide']);
}

function down() {
  if (clusterExists()) run('kind', ['delete', 'cluster', '--name', CLUSTER]);
  fs.rmSync(STATE, { force: true });
}

const [command, ...rest] = process.argv.slice(2);
const commands = { up, test: () => test(rest[0], rest.slice(1)), status, down };
if (!commands[command]) {
  console.error('Usage: node scripts/k8s.mjs up | test <data|ui|load> [args] | status | down');
  process.exit(2);
}
try {
  await commands[command]();
} catch (error) {
  console.error(`\n${error.message}`);
  process.exitCode = 1;
}
